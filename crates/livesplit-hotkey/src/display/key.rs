//! Exhaustive display names for physical keys, with localized composites.
//!
//! Platform glyph selection stays in the platform module. Writing-system labels
//! supplied by the caller bypass this fallback table. Every currently supported
//! key is named explicitly; adding a key requires choosing its display name.

use crate::{
    KeyCode,
    display::{
        Localize, Template, Text,
        platform::{self, Modifier},
    },
};
use core::fmt;

enum Name<L> {
    Literal(&'static str),
    Text(Text),
    Template(Template, Part<L>),
}

enum Part<L> {
    Literal(&'static str),
    Number(u8),
    Key(KeyCode, L),
}

impl<L: Localize> fmt::Display for Part<L> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match *self {
            Self::Literal(text) => f.write_str(text),
            Self::Number(number) => fmt::Display::fmt(&number, f),
            // Only Numpad Backspace/Enter use a base key here. This is one level
            // of composition, not recursive keyboard-layout resolution.
            Self::Key(key, lang) => format(key, lang, f),
        }
    }
}

